#!/usr/bin/env python3
"""
run_deployment_evaluation.py
==============================
Deployment readiness evaluation of the COMPLETE, frozen trust pipeline
(PKI -> B1/SCSV -> MBD -> B2 -> CP -> B3 -> Trust Decision Engine),
replayed against REAL microscopic traffic generated by SUMO (Eclipse
SUMO 1.27.0, installed and run headless in this environment -- see
deployment_eval/sumo_scenario/), not synthetic/toy trajectories.

CARLA and ROS2 are NOT installed in this environment (verified: no
`carla` module, no `ros2` executable) -- this is disclosed honestly in
DEPLOYMENT_EVALUATION.md rather than silently substituted. SUMO is
installed and used for real vehicle kinematics generation; the resulting
FCD (floating car data) trace is then replayed as a live CAM message
stream through the actual, unmodified ISCEPipeline -- both "SUMO" and
"replayed CAM/DENM traffic" from the task's preference list, used
together honestly rather than picking one arbitrarily.

Architecture: ONE persistent ISCEPipeline instance processes the full,
chronologically-ordered, multi-vehicle message stream -- this is the
realistic deployment model (a roadside unit or ego vehicle receiving
interleaved broadcasts from many nearby vehicles), not one pipeline
instance per vehicle. MBD's VehicleHistoryStore is keyed by sender
internally, so a single shared instance correctly disambiguates each
vehicle's own history even though messages interleave.

Does NOT modify B1/MBD/B2/CP/B3/the Trust Decision Engine, and does NOT
retrain B3. Every stage-level timing figure reported here comes from
orchestrator.py's own, pre-existing `latencies` dict -- no new
instrumentation was added inside the pipeline itself.
"""
from __future__ import annotations
import json, os, pathlib, sys, time
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from pipeline.orchestrator import ISCEPipeline
from b1_scsv.scsv import SCSV

HERE = pathlib.Path(__file__).resolve().parent
FCD_PATH = HERE / "sumo_scenario" / "fcd_output.xml"
MESSAGE_BUDGET = 2000   # session wall-clock scope limit; disclosed in the report
WINDOW_SIZE = 5         # CP/cooperative window: last 5 chronological messages
WARMUP_MESSAGES = 20    # messages 0..19 = "cold" region; 20+ = "warm" region


def iter_fcd_events(path):
    """Streams (timestep_seconds, vehicle_id, x, y, speed_mps, angle_deg)
    tuples in file order (already chronological in SUMO's FCD output)."""
    for event, elem in ET.iterparse(str(path), events=("end",)):
        if elem.tag == "timestep":
            t = float(elem.get("time"))
            for v in elem.findall("vehicle"):
                yield (t, v.get("id"), float(v.get("x")), float(v.get("y")),
                       float(v.get("speed")), float(v.get("angle")))
            elem.clear()


def make_flat_message(t_sec, veh_id, x, y, speed_mps, angle_deg):
    return {
        "sender": int(veh_id) if veh_id.isdigit() else abs(hash(veh_id)) % 100000,
        "x": x, "y": y,
        "speed": speed_mps * 3.6,  # km/h, matching to_flat_report's convention
        "heading": angle_deg % 360.0,
        "timestamp": t_sec * 1000.0,  # ms
        "source": "sumo_replay",
    }


def main():
    import psutil
    import torch

    proc = psutil.Process(os.getpid())
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # global (full-trace) concurrency stats, computed once, cheaply, for the
    # real-time feasibility analysis -- independent of how much of the trace
    # is actually replayed through the pipeline below
    concurrency_by_timestep = {}
    for t, veh_id, *_ in iter_fcd_events(FCD_PATH):
        concurrency_by_timestep[t] = concurrency_by_timestep.get(t, 0) + 1
    max_concurrent = max(concurrency_by_timestep.values())
    mean_concurrent = sum(concurrency_by_timestep.values()) / len(concurrency_by_timestep)
    n_timesteps_total = len(concurrency_by_timestep)
    n_messages_total = sum(concurrency_by_timestep.values())

    print(f"Full trace: {n_timesteps_total} timesteps, {n_messages_total} messages, "
          f"max_concurrent={max_concurrent}, mean_concurrent={mean_concurrent:.1f}")
    print(f"Replaying first {MESSAGE_BUDGET} messages (chronological order) through the live pipeline...")

    pipeline = ISCEPipeline(scsv=SCSV(), enable_mbd=True, enable_cp=True, enable_b3=True)

    window = []
    per_message = []
    proc.cpu_percent(interval=None)  # prime the CPU-percent counter
    if device.type == "cuda":
        torch.cuda.reset_peak_memory_stats()

    replay_t0 = time.perf_counter()
    for i, (t_sec, veh_id, x, y, speed_mps, angle_deg) in enumerate(iter_fcd_events(FCD_PATH)):
        if i >= MESSAGE_BUDGET:
            break
        msg = make_flat_message(t_sec, veh_id, x, y, speed_mps, angle_deg)
        window.append(msg)
        if len(window) > WINDOW_SIZE:
            window = window[-WINDOW_SIZE:]

        t0 = time.perf_counter()
        res = pipeline.run(list(window), context="urban")
        wall_ms = (time.perf_counter() - t0) * 1000.0

        row = {
            "i": i, "sim_time_s": t_sec, "vehicle_id": veh_id,
            "decision": res["decision"], "wall_ms": wall_ms,
            **{k: v for k, v in res["latencies"].items()},
        }
        if i % 200 == 0 or i == MESSAGE_BUDGET - 1:
            row["cpu_percent_snapshot"] = proc.cpu_percent(interval=None)
            row["rss_mb_snapshot"] = proc.memory_info().rss / 1e6
            if device.type == "cuda":
                row["gpu_allocated_mb_snapshot"] = torch.cuda.memory_allocated() / 1e6
            print(f"  [{i}/{MESSAGE_BUDGET}] t={t_sec:.1f}s wall_ms={wall_ms:.1f} "
                  f"decision={res['decision']} cpu%={row.get('cpu_percent_snapshot')} "
                  f"rss_mb={row.get('rss_mb_snapshot', 0):.1f}")
        per_message.append(row)

    replay_wall_s = time.perf_counter() - replay_t0
    final_cpu_percent = proc.cpu_percent(interval=None)
    final_rss_mb = proc.memory_info().rss / 1e6
    peak_gpu_mb = (torch.cuda.max_memory_allocated() / 1e6) if device.type == "cuda" else None

    out = {
        "manifest": {
            "experiment": "deployment_evaluation",
            "simulator": "SUMO 1.27.0 (headless), FCD replay",
            "simulators_unavailable": {"CARLA": "not installed in this environment (no `carla` module)",
                                        "ROS2": "not installed in this environment (no `ros2` executable)"},
            "message_budget": MESSAGE_BUDGET,
            "window_size": WINDOW_SIZE,
            "full_trace_n_messages": n_messages_total,
            "full_trace_n_timesteps": n_timesteps_total,
            "full_trace_max_concurrent_vehicles": max_concurrent,
            "full_trace_mean_concurrent_vehicles": mean_concurrent,
            "device": str(device),
            "gpu_name": torch.cuda.get_device_name(0) if device.type == "cuda" else None,
            "note": "Single persistent ISCEPipeline instance (enable_mbd/cp/b3=True, the "
                     "full deployed configuration), realistic multi-vehicle interleaved "
                     "stream. No retraining, no architecture modification.",
        },
        "replay_wall_seconds": replay_wall_s,
        "final_cpu_percent": final_cpu_percent,
        "final_rss_mb": final_rss_mb,
        "peak_gpu_allocated_mb": peak_gpu_mb,
        "per_message": per_message,
    }
    out_path = HERE / "results" / "deployment_eval_results.json"
    out_path.write_text(json.dumps(out, indent=2), encoding="utf-8")
    print(f"\nReplay wall time: {replay_wall_s:.1f}s for {len(per_message)} messages "
          f"({len(per_message)/replay_wall_s:.2f} msg/s)")
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()
